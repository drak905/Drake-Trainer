#!/usr/bin/env python3
"""gen_vi.py - build AI_Vietnamese/Scripts/vi_data.lua.

Sources (later sources override earlier ones for the same key):
  vi_strings.tsv     id, namespace, key, zh, en, vi      complete string-table corpus (English + Chinese keyed)
  vi_zh_strings.tsv  id, zh, vi                          data-table text harvested from the running game (Chinese keyed)
  ui.tsv / extra.tsv English<TAB>Vietnamese              hand-checked UI labels (English keyed)

vi_data.lua returns { exact = {english -> vi}, zh = {chinese -> vi}, tmpl = { {luapattern, vi, {names}} } }.
  * exact : looked up with the English text of an on-screen widget
  * zh    : looked up with the Chinese literal the game passes to GetTextWithNameSpace (a stable key)
  * tmpl  : strings with {placeholders} (matched against the rendered English)
Normalisation (same as main.lua): CRLF -> LF, trim.  Chinese keys are additionally compared whitespace-insensitively.
"""
import os, re, sys, io

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "payload", "mod", "AI_Vietnamese", "Scripts", "vi_data.lua")   # package layout; edit if you run it elsewhere
PH = re.compile(r"\{([A-Za-z_][A-Za-z0-9_]*)\}")
CJK = re.compile(r"[\u3400-\u9fff]")

def norm(s):  return s.replace("\r\n", "\n").replace("\r", "\n").strip()
def unesc(s): return s.replace("\\r", "\r").replace("\\n", "\n").replace("\\t", "\t").replace("\\\\", "\\")
def lua_str(s):
    s = s.replace("\\", "\\\\").replace('"', '\\"').replace("\r", "\\r").replace("\n", "\\n").replace("\t", "\\t")
    return '"' + s + '"'

def lua_pat(en):
    names, out, pos = [], [], 0
    for m in PH.finditer(en):
        out.append(re.sub(r"([%^$().\[\]*+\-?])", r"%\1", en[pos:m.start()]))
        out.append("(.-)"); names.append(m.group(1)); pos = m.end()
    out.append(re.sub(r"([%^$().\[\]*+\-?])", r"%\1", en[pos:]))
    return "^" + "".join(out) + "$", names

def main():
    exact, zh, order_e, order_z = {}, {}, [], []
    def put_en(en, vi):
        k = norm(en)
        if not k or not vi.strip(): return
        if k not in exact: order_e.append(k)
        exact[k] = norm(vi)
    def put_zh(z, vi):
        k = norm(z)
        if not k or not vi.strip() or not CJK.search(k) or norm(vi) == k: return   # junk returned unchanged
        if k not in zh: order_z.append(k)
        zh[k] = norm(vi)

    p = os.path.join(HERE, "vi_strings.tsv")
    for l in open(p, encoding="utf-8"):
        r = l.rstrip("\n").split("\t")
        if len(r) >= 6:
            put_en(unesc(r[4]), unesc(r[5])); put_zh(unesc(r[3]), unesc(r[5]))
    p = os.path.join(HERE, "vi_zh_strings.tsv")
    if os.path.exists(p):
        for l in open(p, encoding="utf-8"):
            r = l.rstrip("\n").split("\t")
            if len(r) >= 3: put_zh(unesc(r[1]), unesc(r[2]))
    p = os.path.join(HERE, "vi_zh_strings_work3.tsv")
    if os.path.exists(p):
        for l in open(p, encoding="utf-8"):
            r = l.rstrip("\n").split("\t")
            if len(r) >= 3: put_zh(unesc(r[1]), unesc(r[2]))
    p = os.path.join(HERE, "extra_zh.tsv")
    if os.path.exists(p):
        for l in open(p, encoding="utf-8"):
            l = l.rstrip("\n").rstrip("\r")
            if not l or l.lstrip().startswith("#") or "\t" not in l: continue
            z, vi = l.split("\t", 1)
            put_zh(unesc(z), unesc(vi))
    for name in ("ui.tsv", "ui_stats.tsv", "extra.tsv"):
        p = os.path.join(HERE, name)
        if not os.path.exists(p): continue
        for l in open(p, encoding="utf-8"):
            l = l.rstrip("\n").rstrip("\r")
            if not l or l.lstrip().startswith("#") or "\t" not in l: continue
            en, vi = l.split("\t", 1)
            put_en(unesc(en.replace("<NL>", "\r\n")), unesc(vi.replace("<NL>", "\r\n")))

    ex, tm = [], []
    for k in order_e:
        if PH.search(k):
            pat, names = lua_pat(k); tm.append((pat, exact[k], names))
        else:
            ex.append((k, exact[k]))
    zhl = [(k, zh[k]) for k in order_z]
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("-- vi_data.lua - GENERATED by tools/afterimage/vi/gen_vi.py. Do not edit by hand.\n")
        f.write("-- %d english-keyed, %d chinese-keyed, %d placeholder templates.\n" % (len(ex), len(zhl), len(tm)))
        f.write("local E = {\n")
        for en, vi in ex: f.write("  [%s] = %s,\n" % (lua_str(en), lua_str(vi)))
        f.write("}\nlocal Z = {\n")
        for z, vi in zhl: f.write("  [%s] = %s,\n" % (lua_str(z), lua_str(vi)))
        f.write("}\nlocal T = {\n")
        for pat, vi, names in tm: f.write("  { %s, %s, { %s } },\n" % (lua_str(pat), lua_str(vi), ", ".join(lua_str(n) for n in names)))
        f.write("}\nreturn { exact = E, zh = Z, tmpl = T }\n")
    sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
    print("english-keyed %d | chinese-keyed %d | templates %d | %.0f KB" % (len(ex), len(zhl), len(tm), os.path.getsize(OUT) / 1024))

if __name__ == "__main__":
    main()
