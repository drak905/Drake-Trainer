"""Generate the winmm.dll forwarding proxy (asm jump stubs + .def) from the real system winmm.dll export table."""
import os, sys
import pefile

REAL = r"C:\Windows\System32\winmm.dll"
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "src")

pe = pefile.PE(REAL)
syms = sorted(pe.DIRECTORY_ENTRY_EXPORT.symbols, key=lambda s: s.ordinal)
base = pe.DIRECTORY_ENTRY_EXPORT.struct.Base
items = []   # (symbol label, name or None, ordinal)
for s in syms:
    if s.name:
        items.append((s.name.decode(), s.name.decode(), s.ordinal))
    else:
        items.append(("gsvi_ord%d" % s.ordinal, None, s.ordinal))

with open(os.path.join(OUT, "winmm.def"), "w", encoding="ascii", newline="\r\n") as f:
    f.write("LIBRARY winmm\r\nEXPORTS\r\n")
    for label, name, ordv in items:
        if name:
            f.write("    %s @%d\r\n" % (name, ordv))
        else:
            f.write("    %s @%d NONAME\r\n" % (label, ordv))

with open(os.path.join(OUT, "winmm_proxy.inc"), "w", encoding="ascii", newline="\n") as f:
    f.write("/* generated by gen_proxy.py from %s - do not edit */\n" % REAL)
    f.write("#define GSVI_PROXY_COUNT %d\n" % len(items))
    f.write("void *gsvi_proxy_tab[GSVI_PROXY_COUNT];\n")
    f.write("static const char *const gsvi_proxy_names[GSVI_PROXY_COUNT] = {\n")
    for label, name, ordv in items:
        f.write('    %s,\n' % ('"%s"' % name if name else "0"))
    f.write("};\n")
    f.write("static const unsigned short gsvi_proxy_ords[GSVI_PROXY_COUNT] = {\n")
    for label, name, ordv in items:
        f.write("    %d,\n" % ordv)
    f.write("};\n")
    f.write("__asm__(\n\".text\\n\"\n")
    for i, (label, name, ordv) in enumerate(items):
        f.write('".globl %s\\n"\n"%s:\\n"\n"    jmp *gsvi_proxy_tab+%d(%%rip)\\n"\n' % (label, label, i * 8))
    f.write(");\n")
print("exports:", len(items), "ordinal-only:", sum(1 for i in items if i[1] is None))
