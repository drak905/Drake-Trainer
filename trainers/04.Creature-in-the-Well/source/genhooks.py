"""genhooks.py - emit hooks_gen.h for the CITW trainer from PDB symbol names (capstone + pefile).
For every hook target: stolen prologue length (>=5 bytes, whole instructions), relocation table for the stolen
instructions, and a unique AOB pattern (rel32/rip-rel displacements wildcarded) so the DLL can re-locate it after a patch."""
import re, sys, json, hashlib, capstone
from cdis import data, rva2off, pe, EXE, syms
TARGETS = [  # (id, symbol)
 ("SetHealthImpl",   "AHeroCharacter::SetHealthImpl"),
 ("SetTemplePower",  "AHeroPlayerController::SetTemplePower"),
 ("MoveDash",        "UHeroMovementComponent::Dash"),
 ("MoveMaxSpeed",    "UHeroMovementComponent::GetMaxSpeed"),
 ("MoveMaxAccel",    "UHeroMovementComponent::GetMaxAcceleration"),
 ("AttackPower",     "AHeroCharacter::GetAttackPower"),
 ("PcTick",          "AHeroPlayerController::Tick"),
 ("HeroTick",        "AHeroCharacter::Tick"),
]
CALLS = [  # plain function pointers the DLL calls (no hook)
 ("fnAddTemplePower", "AHeroPlayerController::AddTemplePower"),
 ("fnGetTemplePower", "AHeroPlayerController::GetTemplePower"),
 ("fnSetHealth",      "AHeroCharacter::SetHealth"),
 ("fnGetUser",        "AHeroPlayerController::GetPersistentUser"),
 ("fnSlotValid",      "AHeroPlayerController::IsActiveSaveSlotValid"),
 ("fnLoadSlot",       "AHeroPlayerController::LoadSaveSlot"),
]
text = [s for s in pe.sections if s.Name.startswith(b".text")][0]
tbase = text.VirtualAddress; tdata = data[text.PointerToRawData: text.PointerToRawData + text.Misc_VirtualSize]
sym = {n: (a, s) for a, s, n in syms if s > 0}
md = capstone.Cs(capstone.CS_ARCH_X86, capstone.CS_MODE_64); md.detail = True
def disasm(rva, n): return list(md.disasm(data[rva2off(rva): rva2off(rva) + n], rva))
def wild(ins, strict=True):
    out = []
    if ins.disp_size == 4 and any(op.type == capstone.x86.X86_OP_MEM and op.mem.base == capstone.x86.X86_REG_RIP for op in ins.operands):
        out.append((ins.disp_offset, 4))
    if not strict: return out
    if ins.mnemonic in ("call", "jmp") and ins.bytes[0] in (0xE8, 0xE9): out.append((1, 4))
    elif ins.mnemonic.startswith("j") and ins.bytes[0] == 0x0F: out.append((2, 4))
    return out
def build(rva, size):
    ins = disasm(rva, max(size, 64) + 32)
    # stolen prologue
    stolen = 0; relocs = []
    for i in ins:
        if stolen >= 5: break
        w = wild(i)
        if i.mnemonic.startswith("j") or i.mnemonic == "call" or i.mnemonic == "loop":
            if not w: raise SystemExit("short branch in stolen prologue @%x: %s %s" % (i.address, i.mnemonic, i.op_str))
        for (doff, dsz) in w: relocs.append((i.address - rva, doff, i.size))
        stolen += i.size
    # internal branch into the patched area?
    fn_end = rva + size
    for i in disasm(rva, size):
        if (i.mnemonic.startswith("j") and i.operands and i.operands[0].type == capstone.x86.X86_OP_IMM):
            t = i.operands[0].imm
            if rva < t < rva + stolen: raise SystemExit("branch into stolen area @%x -> %x" % (i.address, t))
    # unique AOB
    allins = ins
    for strict, want in [(s_, w_) for s_ in (True, False) for w_ in range(24, 129, 8)]:
        pat = []; n = 0
        for i in allins:
            if n >= want: break
            b = list(i.bytes)
            for (doff, dsz) in wild(i, strict):
                for k in range(dsz): b[doff + k] = None
            pat += b; n += i.size
        rx = re.compile(b"".join((re.escape(bytes([x])) if x is not None else b".") for x in pat), re.S)
        m = list(rx.finditer(tdata))
        if len(m) == 1:
            assert m[0].start() + tbase == rva
            return stolen, relocs, pat
    raise SystemExit("no unique AOB for %x" % rva)
def pat_str(pat): return " ".join("??" if x is None else "%02X" % x for x in pat)
out = ["/* generated by tools/citw/genhooks.py - do not edit. exe sha256 %s */" % hashlib.sha256(data).hexdigest().upper(),
       "#ifndef HOOKS_GEN_H\n#define HOOKS_GEN_H", "typedef struct { unsigned char off, disp, len; } Reloc;",
       "typedef struct { const char* name; unsigned rva; unsigned char stolen, nreloc; Reloc rel[4]; const char* aob; } HookDef;"]
rows = []; ids = []
for hid, name in TARGETS:
    rva, size = sym[name]; st, rl, pat = build(rva, size)
    assert len(rl) <= 4
    rows.append('  { "%s", 0x%X, %d, %d, {%s}, "%s" }, /* %s size %d */' % (hid, rva, st, len(rl),
        ", ".join("{%d,%d,%d}" % r for r in rl) or "{0,0,0}", pat_str(pat), name, size))
    ids.append(hid)
out.append("enum { " + ", ".join("H_" + i for i in ids) + ", H_COUNT };")
out.append("static const HookDef kHooks[H_COUNT] = {\n" + "\n".join(rows) + "\n};")
out.append("typedef struct { const char* name; unsigned rva; const char* aob; } FnDef;")
rows = []
for fid, name in CALLS:
    rva, size = sym[name]; st, rl, pat = build(rva, size)
    rows.append('  { "%s", 0x%X, "%s" }, /* %s */' % (fid, rva, pat_str(pat), name))
out.append("enum { " + ", ".join("F_" + c[0][2:] for c in CALLS) + ", F_COUNT };")
out.append("static const FnDef kFns[F_COUNT] = {\n" + "\n".join(rows) + "\n};")
out.append("#endif")
open("hooks_gen.h", "w").write("\n".join(out) + "\n")
print("\n".join(out))



